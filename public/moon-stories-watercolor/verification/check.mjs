import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const context=vm.createContext({});
for(const file of ['story-data.js','story-engine.js','guide.js'])vm.runInContext(fs.readFileSync(path.join(root,'js',file),'utf8'),context);
const {DialogueState,SceneManager,AnimationController}=context.MoonStory;
const lines=context.MoonStoryData.opening.lines;
assert.equal(lines.length,8);
assert.equal(lines[0].speaker,'Narrator');
assert.equal(lines[7].text,'Not this time. Come on!');
const state=new DialogueState(lines);
state.previous();assert.equal(state.index,0);
for(let i=0;i<15;i++)state.next();assert.equal(state.index,7);assert(state.last);
state.previous();assert.equal(state.index,6);state.replay();assert.equal(state.index,0);
const calls=[];const manager=new SceneManager();
manager.register('a',{enter(){calls.push('enter-a')},exit(){calls.push('exit-a')},next(){calls.push('next-a')}});
manager.register('b',{enter(){calls.push('enter-b')},exit(){calls.push('exit-b')}});
manager.enter('a');manager.next();manager.enter('b');manager.exit();
assert.deepEqual(calls,['enter-a','next-a','exit-a','enter-b','exit-b']);
assert.throws(()=>manager.enter('missing'));
let played=false;new AnimationController(()=>true).play({animate(){played=true}},[]);assert.equal(played,false);
const guide=context.CuoiGuide;
assert.equal(guide.answerFor('Who is Cuoi?'),guide.answers.cuoi);
assert.equal(guide.answerFor('I feel lonely'),guide.answers.feelings);
assert.equal(guide.answerFor('How do I turn sound off?'),guide.answers.sound);
assert.equal(guide.answerFor('<script>alert(1)</script>'),guide.answers.fallback);
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
assert(html.includes('data-open-story'));assert(html.includes('id="cuoi-guide"'));
assert(!html.includes('<symbol'));assert(!html.includes('<use'));
assert(!fs.readFileSync(path.join(root,'js/story-engine.js'),'utf8').includes('createElementNS'));
console.log('PASS: dialogue boundaries/replay, scene lifecycle, reduced motion, curated guide routing, native image-based rendering and CTA hooks.');
